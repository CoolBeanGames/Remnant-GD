"""Original, deterministic metre-scale PBR maps for the warehouse asset set."""
from pathlib import Path
import numpy as np
from PIL import Image, ImageDraw, ImageFilter

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'Models/Architecture/DilapidatedWarehouse/Textures'
OUT.mkdir(parents=True, exist_ok=True)
(OUT / '.gdignore').write_text('')
N = 1024
y, x = np.mgrid[0:N, 0:N] / N


def noise(seed, frequencies=(4, 12, 40, 160)):
    rng = np.random.default_rng(seed)
    result = np.zeros((N, N))
    for index, frequency in enumerate(frequencies):
        small = rng.random((frequency, frequency))
        # A wrapped border gives the resampler continuous tile edges.
        padded = np.pad(small, 1, mode='wrap')
        im = Image.fromarray(np.uint8(padded * 255)).resize(
            (N + 2 * N // frequency, N + 2 * N // frequency), Image.Resampling.BICUBIC)
        start = N // frequency
        result += np.asarray(im)[start:start+N, start:start+N] / 255 / 2**index
    return result / sum(1 / 2**i for i in range(len(frequencies)))


def save(name, colour, height, roughness, metal=None):
    if colour.ndim == 1:
        colour = np.broadcast_to(colour, (N, N, 3)).copy()
    Image.fromarray(np.uint8(np.clip(colour, .008, .99) * 255)).save(OUT / f'{name}_albedo.png')
    dy, dx = np.gradient(height)
    normal = np.stack((-dx * 24, -dy * 24, np.ones_like(dx)), axis=-1)
    normal /= np.linalg.norm(normal, axis=-1)[..., None]
    Image.fromarray(np.uint8((normal * .5 + .5) * 255)).save(OUT / f'{name}_normal.png')
    Image.fromarray(np.uint8(np.clip(roughness + np.zeros((N, N)), .08, .99) * 255)).save(OUT / f'{name}_roughness.png')
    if metal is not None:
        Image.fromarray(np.uint8(np.clip(metal + np.zeros((N, N)), 0, 1) * 255)).save(OUT / f'{name}_metallic.png')


macro, fine = noise(81), noise(82, (20, 70, 220, 450))
cracks = Image.new('L', (N, N), 0)
d = ImageDraw.Draw(cracks)
rng = np.random.default_rng(500)
for start in ((110, 0), (1024, 630), (620, 1024)):
    points = [start]
    direction = rng.uniform(1, 5)
    for i in range(16):
        direction += rng.uniform(-.7, .7)
        last = points[-1]
        points.append((last[0] + np.cos(direction) * 32, last[1] + np.sin(direction) * 32))
    d.line(points, fill=180, width=2)
crack = np.asarray(cracks.filter(ImageFilter.GaussianBlur(.4))) / 255
concrete = np.array([.39, .385, .345]) + (macro-.5)[..., None] * .19 + (fine-.5)[..., None] * .1
concrete -= crack[..., None] * .22
save('concrete', concrete, fine*.6+macro*.3-crack*.22, .88 + (macro-.5)*.12)

# 1.2m-wide brick scan: four courses, staggered mortar joints.
rows = np.floor(y * 8).astype(int)
bx = (x*4 + (rows % 2)*.5) % 1
by = (y*8) % 1
joint = (bx < .037) | (bx > .968) | (by < .052) | (by > .947)
brick = np.array([.31, .205, .14]) + (noise(73)-.5)[..., None]*.23
brick[joint] = np.array([.33, .32, .27])
save('brick', brick, noise(77)*.25 + (~joint)*.6, .94)

for name, base, seed in [('plaster', [.51,.50,.41],90), ('wood',[.24,.16,.095],94),
                         ('rubber',[.025,.028,.026],99)]:
    h = noise(seed)
    if name == 'wood':
        fibres = noise(96, (8, 30, 140))
        fibres = np.asarray(Image.fromarray(np.uint8(fibres*255)).resize((N, 40)).resize((N,N), Image.Resampling.BICUBIC))/255
        h = fibres*.6 + h*.4
    save(name, np.array(base)+(h-.5)[...,None]*(.18 if name!='rubber' else .035), h, .9 if name!='rubber' else .62)

oxide = noise(154)
rust_colour = np.array([.255, .12, .047]) + (oxide-.5)[...,None] * np.array([.35,.15,.07])
save('rust', rust_colour, oxide, .87+(oxide-.5)*.17, .12)
steel = noise(22)
save('steel', np.array([.29,.31,.30])+(steel-.5)[...,None]*.11, steel*.25, .46+(steel-.5)*.3, .87)
for name, base, seed in [('paint_green',[.14,.25,.20],4),('paint_yellow',[.57,.38,.075],8),('paint_cream',[.57,.54,.43],11)]:
    h = noise(seed)
    chipped = np.clip((noise(seed+36)-.47)*8, 0, 1)
    paint = np.array(base) + (h-.5)[...,None]*.14
    col = paint*(1-chipped[...,None]) + rust_colour*chipped[...,None]
    save(name, col, h*.23+chipped*.55, .59+chipped*.3, chipped*.22)

# Exportable alpha decals: perimeter fades keep large localized damage organic.
for name, colour, seed, edge_power in [('damp',[35,33,24],31,1.4),('oil',[25,23,18],49,2.2),('dust',[103,93,65],59,.9)]:
    n = noise(seed)
    edge = (np.sin(np.pi*x)*np.sin(np.pi*y))**edge_power
    alpha = np.clip(edge*(n*.9+.1)*1.2,0,.84)
    rgba = np.zeros((N,N,4),dtype=np.uint8)
    rgba[...,:3] = colour
    rgba[...,3] = np.uint8(alpha*255)
    Image.fromarray(rgba).save(OUT / f'{name}_decal.png')
(OUT/'PROVENANCE.md').write_text('# Warehouse textures\n\nAll maps are original, deterministic NumPy/Pillow artwork generated by `Tools/make_warehouse_textures.py`; no downloaded photographs or models. Metre-scale UV mapping and localized transparent decals provide concrete fissures, staggered brick courses, flaking enamel, oxidized steel, oil and damp. Native files pack their used maps; GLBs embed export-supported PBR channels.\n')
print('Warehouse PBR maps:', OUT)
